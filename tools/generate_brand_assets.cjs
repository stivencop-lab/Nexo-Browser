#!/usr/bin/env node
// Nexo UI 7.0 «Liquid Craft»: monograma "N" geométrico y monocromático, una sola geometría
// para el icono adaptable, el icono temático, el emblema interno y la notificación.
// Sin degradados: tinta sólida #F4F4F5 sobre lienzo Obsidian #09090B.
// Run from any directory: node tools/generate_brand_assets.cjs
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const INK = '#F4F4F5';
const CANVAS = '#09090B';
// Tallos de 7.2u y diagonal limpia; todos los puntos dentro del círculo seguro de 66dp.
const N = 'M39,70 V38 H46.2 L61.8,58.6 V38 H69 V70 H61.8 L46.2,49.4 V70 Z';
function vector(body, size = 108, viewport = 108) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_brand_assets.cjs. Edit the source geometry there. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${size}dp" android:height="${size}dp"
    android:viewportWidth="${viewport}" android:viewportHeight="${viewport}">
${body}
</vector>\n`;
}
const glyph = color => `    <path android:fillColor="${color}" android:pathData="${N}" />`;
const enlarge = body => `    <group android:pivotX="54" android:pivotY="54" android:scaleX="1.5" android:scaleY="1.5">\n${body}\n    </group>`;
const roundedSquare = 'M24,0 H84 Q108,0 108,24 V84 Q108,108 84,108 H24 Q0,108 0,84 V24 Q0,0 24,0 Z';
const outputs = {
  'app/src/main/res/drawable/ic_launcher_background.xml': vector(`    <path android:fillColor="${CANVAS}" android:pathData="M0,0 H108 V108 H0 Z" />`),
  'app/src/main/res/drawable/ic_launcher_foreground.xml': vector(glyph(INK)),
  'app/src/main/res/drawable/ic_launcher_monochrome.xml': vector(glyph('#FFFFFFFF')),
  // Glifo tintable para vistas internas (la losa se dibuja en código con NexoMonogramDrawable).
  'app/src/main/res/drawable/ic_nexo_logo.xml': vector(enlarge(glyph('#FFFFFFFF')), 24),
  'app/src/main/res/drawable/ic_nexo_emblem.xml': vector(enlarge(glyph('#FFFFFFFF')), 48),
  'app/src/main/res/drawable/ic_stat_nexo.xml': vector(enlarge(glyph('#FFFFFFFF')), 24),
};
outputs['docs/brand/nexo.svg'] = `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 108 108" role="img" aria-label="Nexo Browser">
<!-- Generated by tools/generate_brand_assets.cjs. -->
<path d="${roundedSquare}" fill="${CANVAS}"/>
<g transform="translate(54 54) scale(1.5) translate(-54 -54)"><path d="${N}" fill="${INK}"/></g>
</svg>\n`;
for (const [name, content] of Object.entries(outputs)) {
  const dest = path.join(root, name);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, content);
}
console.log('Updated six Android vector drawables and the SVG brand preview.');
